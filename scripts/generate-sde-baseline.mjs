#!/usr/bin/env node
// Refreshes the compact public SDE baseline from canonical settlement artifacts.
// Run from this repository with ../settlement-cycle checked out alongside it.
import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";

const settlementRoot = resolve(process.cwd(), "../settlement-cycle/settlements");
const primes = ["grove", "spark"];
const allowed = new Set(["grove:E8", "grove:E9", "grove:E10", "spark:S21", "spark:S24", "spark:S62"]);
const byDate = new Map();

function addResult(prime, result, includeAllDays) {
  const named = new Map();
  const allNamedTotals = new Map();
  for (const venue of result.sde_daily_breakdown ?? []) {
    for (const day of venue.daily ?? []) {
      const value = Number(day.cum_value);
      allNamedTotals.set(day.block_date, (allNamedTotals.get(day.block_date) ?? 0) + value);
      if (!allowed.has(`${prime}:${venue.venue_id}`)) continue;
      const values = named.get(day.block_date) ?? {};
      values[`${prime}:${venue.venue_id}`] = value;
      named.set(day.block_date, values);
    }
  }
  for (const day of result.sky_revenue_daily ?? []) {
    const values = named.get(day.date) ?? {};
    const subtotal = allNamedTotals.get(day.date) ?? 0;
    const residual = Number(day.sde_av) - subtotal;
    values[`${prime}:psm3`] = Math.max(0, Math.abs(residual) < 0.01 ? 0 : residual);
    named.set(day.date, values);
  }
  const dates = [...named.keys()].sort();
  const selected = includeAllDays ? dates : dates.slice(-1);
  for (const date of selected) {
    const primesForDate = byDate.get(date) ?? {};
    primesForDate[prime] = named.get(date);
    byDate.set(date, primesForDate);
  }
}

for (let month = 1; month <= 8; month += 1) {
  const key = `2026-${String(month).padStart(2, "0")}`;
  for (const prime of primes) {
    const path = resolve(settlementRoot, prime, key, "provenance.json");
    addResult(prime, JSON.parse(readFileSync(path, "utf8")), month >= 6);
  }
}

const points = [...byDate.entries()]
  .filter(([, values]) => values.grove && values.spark)
  .sort(([a], [b]) => a.localeCompare(b))
  .map(([date, values]) => {
    const venues = { ...values.grove, ...values.spark };
    const totalUsd = Object.values(venues).reduce((sum, value) => sum + value, 0);
    return { date, totalUsd, venues };
  });

const target = resolve(process.cwd(), "src/sde-baseline.ts");
const header = `// Generated by scripts/generate-sde-baseline.mjs from canonical monthly settlement artifacts.\n`;
writeFileSync(target, `${header}import type { DirectExposurePoint } from "./types.js";\n\nexport const sdeBaselinePoints: DirectExposurePoint[] = ${JSON.stringify(points, null, 2)};\n`);
console.log(`Wrote ${points.length} points to ${target}`);
