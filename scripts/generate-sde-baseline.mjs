#!/usr/bin/env node
// Compiles the reviewed immutable JSON history into the TypeScript bundle.
import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";

const historyPath = resolve(process.cwd(), "src/data/sde-history.json");
const history = JSON.parse(readFileSync(historyPath, "utf8"));
if (!Array.isArray(history.points) || history.points.length === 0) throw new Error("SDE history JSON has no points");
const points = history.points;

const target = resolve(process.cwd(), "src/sde-baseline.ts");
const header = `// Generated by scripts/generate-sde-baseline.mjs from src/data/sde-history.json.\n`;
writeFileSync(target, `${header}import type { DirectExposurePoint } from "./types.js";\n\nexport const sdeBaselinePoints: DirectExposurePoint[] = ${JSON.stringify(points, null, 2)};\n`);
console.log(`Wrote ${points.length} points to ${target}`);
